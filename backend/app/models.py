"""
Data models and schemas for DemoToSkill.
Includes Pydantic v2 schemas for workflows, steps, candidates, healing,
Gemma call logging, and LangGraph TypedDict states.
"""

from typing import Literal, Optional, Any, TypedDict
from pydantic import BaseModel, Field



class Locator(BaseModel):
    """Represents a Playwright locator strategy."""
    kind: Literal['role', 'label', 'placeholder', 'text', 'testid', 'css']
    value: str
    name: Optional[str] = None


class Step(BaseModel):
    """Represents a single step in a workflow."""
    idx: int
    action: Literal['goto', 'click', 'fill', 'select', 'check', 'press']
    locators: list[Locator] = Field(default_factory=list)
    value: Optional[str] = None
    intent: str = ''
    shot_before: str = ''
    shot_after: str = ''
    dom_context: str = ''


class Variable(BaseModel):
    """Represents a dynamic parameter in the workflow."""
    name: str
    type: Literal['text', 'select', 'date', 'number'] = 'text'
    example: str = ''
    options: list[str] = Field(default_factory=list)


class SuccessCondition(BaseModel):
    """Evaluation criteria for verifying workflow completion."""
    text_visible: Optional[str] = None
    url_contains: Optional[str] = None
    visual: str = ''


class WorkflowSpec(BaseModel):
    """Canonical specification for an automated skill."""
    id: Optional[str] = None
    name: str
    start_url: str
    variables: list[Variable] = Field(default_factory=list)
    steps: list[Step] = Field(default_factory=list)
    success: SuccessCondition



class StepResult(BaseModel):
    """Result of executing a single step on a page."""
    idx: int
    ok: bool
    error: Optional[str] = None
    shot: Optional[str] = None
    resolved_locator: Optional[Locator] = None
    duration_ms: Optional[float] = None


class RowResult(BaseModel):
    """Result of running a workflow over one set of variable inputs."""
    row_idx: int
    row_data: dict[str, Any]
    steps: list[StepResult] = Field(default_factory=list)
    success: Optional[bool] = None
    evidence: Optional[str] = None
    final_shot: Optional[str] = None



class CandidateElement(BaseModel):
    """A DOM candidate extracted from the live page for Set-of-Marks healing."""
    id: int
    tag: str
    role: Optional[str] = None
    text: Optional[str] = None
    aria_label: Optional[str] = None
    placeholder: Optional[str] = None
    id_attr: Optional[str] = None
    classes: list[str] = Field(default_factory=list)
    bbox: dict[str, float] = Field(default_factory=dict)
    bm25_score: float = 0.0


class HealProposal(BaseModel):
    """Heal proposal generated by Gemma 4 via Set-of-Marks visual prompt."""
    step_idx: int
    choice: Optional[int] = None
    confidence: float = 0.0
    reason: str = ''
    marked_shot: str = ''
    original_shot: str = ''
    candidate: Optional[CandidateElement] = None
    proposed_locator: Optional[Locator] = None



class UnderstandStepOutput(BaseModel):
    """Output schema for Gemma 4 pass 1: per-step understanding."""
    intent: str
    role: Literal['variable', 'constant']
    variable_name: Optional[str] = None
    field_type: Optional[Literal['text', 'select', 'date', 'number']] = None
    confidence: float = 0.0


class UnderstandWorkflowOutput(BaseModel):
    """Output schema for Gemma 4 pass 2: workflow synthesis."""
    name: str
    variables: list[Variable] = Field(default_factory=list)
    success: SuccessCondition


class HealChoiceOutput(BaseModel):
    """Output schema for Gemma 4 Set-of-Marks visual choice."""
    choice: Optional[int] = None
    confidence: float = 0.0
    reason: str = ''


class VerifyVisualOutput(BaseModel):
    """Output schema for Gemma 4 visual verification."""
    success: bool
    evidence: str
    confidence: float = 0.0



class GemmaCallLog(BaseModel):
    """Log record for inspection of Gemma 4 API calls."""
    id: str
    timestamp: str
    endpoint: Literal['understand_step', 'understand_workflow', 'heal_choice', 'verify_visual', 'smoke_test']
    model: str
    prompt_summary: str
    image_paths: list[str] = Field(default_factory=list)
    response_raw: str
    parsed_json: Optional[dict[str, Any]] = None
    latency_ms: float
    status: Literal['success', 'retry', 'error']
    error: Optional[str] = None



class CompileState(TypedDict, total=False):
    """State dictionary for the LangGraph Compile Graph."""
    recording_id: str
    raw_steps: list[Step]
    intents_approved: bool
    spec: Optional[WorkflowSpec]
    trial_rows: list[dict[str, Any]]
    results: list[RowResult]
    repairs_count: int
    status: Literal[
        'idle', 'understanding', 'review_pending', 'compiling',
        'testing', 'verifying', 'repairing', 'saved', 'failed'
    ]
    error: Optional[str]


class RunState(TypedDict, total=False):
    """State dictionary for the LangGraph Run Graph."""
    run_id: str
    spec_id: str
    spec: WorkflowSpec
    rows: list[dict[str, Any]]
    current_row_idx: int
    results: list[RowResult]
    failed_step: Optional[Step]
    heal_proposal: Optional[HealProposal]
    heal_approved: bool
    status: Literal['running', 'heal_pending', 'patched', 'completed', 'failed']
    error: Optional[str]

